package dev.resilience4cata;

import java.lang.reflect.Array;
import java.lang.reflect.Constructor;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.stream.Collectors;

/**
 * Entry point: applies the policies declared by annotations, in one of two styles.
 *
 * <ul>
 *   <li>{@link #of(Class, Object, ResilienceRegistry) of}: wraps an implementation of an annotated
 *       interface. Only the interface's annotations count, and calls the implementation makes to itself
 *       are not intercepted.
 *   <li>{@link #create(Class, ResilienceRegistry, Object...) create}: instantiates the generated subclass
 *       of an annotated non-final class. The class's annotations win over those of its interfaces,
 *       attribute by attribute, and calls such as {@code this.other()} inside the class go through
 *       {@code other()}'s policies.
 * </ul>
 */
public final class Resilient {

    /** Suffix of the classes generated by the annotation processor. */
    public static final String GENERATED_SUFFIX = "$Resilient";

    private Resilient() {
    }

    /**
     * Wraps {@code delegate} with the policies declared on {@code type}. Looks up the generated class
     * once; calls on the returned object use no reflection.
     *
     * @param type the annotated interface
     * @param delegate the implementation to protect
     * @param registry the configurations to use
     * @param <T> the interface type
     * @return an object that implements {@code type} and applies its policies
     * @throws IllegalArgumentException if {@code type} is not an interface, or a configuration is invalid
     * @throws IllegalStateException if the annotation processor did not run on {@code type}
     */
    public static <T> T of(Class<T> type, T delegate, ResilienceRegistry registry) {
        Objects.requireNonNull(type, "type");
        Objects.requireNonNull(delegate, "delegate");
        Objects.requireNonNull(registry, "registry");
        if (!type.isInterface()) {
            throw new IllegalArgumentException(type.getName() + " is not an interface. For an annotated class, use"
                    + " Resilient.create(" + type.getSimpleName() + ".class, registry).");
        }
        if (!type.isInstance(delegate)) {
            throw new IllegalArgumentException(delegate.getClass().getName() + " does not implement " + type.getName());
        }
        String generatedName = type.getName() + GENERATED_SUFFIX;
        Class<?> generated = generated(type, generatedName);
        try {
            Constructor<?> constructor = generated.getConstructor(type, ResilienceRegistry.class);
            return type.cast(constructor.newInstance(delegate, registry));
        } catch (InvocationTargetException e) {
            Throwable cause = e.getCause();
            if (cause instanceof RuntimeException runtime) {
                throw runtime;
            }
            if (cause instanceof Error error) {
                throw error;
            }
            throw new IllegalStateException("Could not create " + generatedName, cause);
        } catch (NoSuchMethodException e) {
            throw new IllegalStateException(generatedName + " was generated by an incompatible version of the"
                    + " annotation processor. Use the same version for resilience4cata-core and resilience4cata-processor.", e);
        } catch (IllegalAccessException e) {
            throw new IllegalStateException("Cannot access " + generatedName + ". If your code is a named module,"
                    + " add 'exports " + type.getPackageName() + " to dev.resilience4cata.core;' to its module-info.java.", e);
        } catch (InstantiationException e) {
            throw new IllegalStateException("Could not create " + generatedName, e);
        }
    }

    /**
     * Creates an instance of the subclass generated for the annotated class {@code type}, calling the
     * constructor of {@code type} that takes {@code arguments}. Looks up the generated class and its
     * constructor once, by reflection; calls on the returned object use no reflection.
     *
     * <p>The generated class {@code <type>$Resilient} mirrors every non-private constructor of
     * {@code type} with a leading {@code ResilienceRegistry} parameter, so code that wants compile-time
     * checking (or must pass {@code null} to an overloaded constructor) can call it directly instead:
     * {@code new InventoryService$Resilient(registry, repository)}.
     *
     * <p>Methods that the constructor of {@code type} calls on {@code this} run before the policies are
     * set up, so they must not be annotated.
     *
     * @param type the annotated, non-final class
     * @param registry the configurations to use
     * @param arguments the arguments of the constructor of {@code type} to call; none for the no-argument one
     * @param <T> the class type
     * @return an instance of {@code type} that applies its policies, including to calls it makes to itself
     * @throws IllegalArgumentException if {@code type} is an interface, a final, abstract, local or anonymous
     *     class, if no constructor (or more than one) accepts {@code arguments}, or a configuration is invalid
     * @throws IllegalStateException if the annotation processor did not run on {@code type}
     */
    public static <T> T create(Class<T> type, ResilienceRegistry registry, Object... arguments) {
        Objects.requireNonNull(type, "type");
        Objects.requireNonNull(registry, "registry");
        Objects.requireNonNull(arguments, "arguments");
        if (type.isInterface()) {
            throw new IllegalArgumentException(type.getName() + " is an interface. Use Resilient.of("
                    + type.getSimpleName() + ".class, implementation, registry) to wrap an implementation of it.");
        }
        if (type.isLocalClass() || type.isAnonymousClass() || type.isPrimitive() || type.isArray()
                || type.isEnum() || type.isRecord() || Modifier.isFinal(type.getModifiers())
                || Modifier.isAbstract(type.getModifiers())) {
            throw new IllegalArgumentException(type.getName() + " cannot be extended by a generated subclass: only"
                    + " top-level or static nested classes that are neither final nor abstract can. Annotate an"
                    + " interface instead and use Resilient.of(...).");
        }
        String generatedName = type.getName() + GENERATED_SUFFIX;
        Class<?> generated = generated(type, generatedName);
        if (generated.getSuperclass() != type) {
            throw new IllegalStateException(generatedName + " does not extend " + type.getName() + ". It was generated"
                    + " by an incompatible version of the annotation processor: use the same version for"
                    + " resilience4cata-core and resilience4cata-processor.");
        }
        Object[] all = new Object[arguments.length + 1];
        all[0] = registry;
        System.arraycopy(arguments, 0, all, 1, arguments.length);
        Call call = constructor(generated, all);
        try {
            return type.cast(call.constructor().newInstance(call.arguments()));
        } catch (InvocationTargetException e) {
            Throwable cause = e.getCause();
            if (cause instanceof RuntimeException runtime) {
                throw runtime;
            }
            if (cause instanceof Error error) {
                throw error;
            }
            throw new IllegalStateException("Could not create " + generatedName, cause);
        } catch (IllegalAccessException e) {
            throw new IllegalStateException("Cannot access " + generatedName + ". If your code is a named module,"
                    + " add 'exports " + type.getPackageName() + " to dev.resilience4cata.core;' to its module-info.java.", e);
        } catch (InstantiationException e) {
            throw new IllegalStateException("Could not create " + generatedName, e);
        }
    }

    private static Class<?> generated(Class<?> type, String generatedName) {
        try {
            return Class.forName(generatedName, true, type.getClassLoader());
        } catch (ClassNotFoundException e) {
            throw new IllegalStateException("No generated class " + generatedName + " found. Make sure that "
                    + type.getName() + " has at least one resilience annotation, and that the annotation processor"
                    + " runs when it is compiled. With Gradle:\n"
                    + "    annotationProcessor 'dev.resilience4cata:resilience4cata-processor:<version>'", e);
        }
    }

    /** A constructor of a generated subclass and the arguments to call it with, the registry first. */
    private record Call(Constructor<?> constructor, Object[] arguments) {
    }

    /**
     * Picks the public constructor of a generated subclass that accepts {@code arguments} (the registry
     * first), like the compiler would: without varargs expansion if possible, otherwise with it. Primitive
     * parameters accept their wrapper, never null. Fails if no constructor or more than one fits.
     */
    private static Call constructor(Class<?> generated, Object[] arguments) {
        List<Call> exact = new ArrayList<>();
        List<Call> expanded = new ArrayList<>();
        List<String> available = new ArrayList<>();
        for (Constructor<?> candidate : generated.getConstructors()) {
            Class<?>[] parameters = candidate.getParameterTypes();
            if (parameters.length == 0 || parameters[0] != ResilienceRegistry.class) {
                continue;
            }
            available.add(signature(candidate));
            if (parameters.length == arguments.length && accepts(parameters, arguments, parameters.length)) {
                exact.add(new Call(candidate, arguments));
            } else if (candidate.isVarArgs() && arguments.length >= parameters.length - 1
                    && accepts(parameters, arguments, parameters.length - 1)) {
                Class<?> component = parameters[parameters.length - 1].getComponentType();
                Object array = Array.newInstance(component, arguments.length - parameters.length + 1);
                boolean fits = true;
                for (int i = parameters.length - 1; i < arguments.length && fits; i++) {
                    fits = accepts(component, arguments[i]);
                    if (fits) {
                        Array.set(array, i - parameters.length + 1, arguments[i]);
                    }
                }
                if (fits) {
                    Object[] packed = Arrays.copyOf(arguments, parameters.length);
                    packed[parameters.length - 1] = array;
                    expanded.add(new Call(candidate, packed));
                }
            }
        }
        List<Call> matches = exact.isEmpty() ? expanded : exact;
        if (matches.size() == 1) {
            return matches.get(0);
        }
        if (available.isEmpty()) {
            throw new IllegalStateException(generated.getName() + " was generated by an incompatible version of the"
                    + " annotation processor. Use the same version for resilience4cata-core and resilience4cata-processor.");
        }
        String given = Arrays.stream(arguments).skip(1).map(a -> a == null ? "null" : a.getClass().getSimpleName())
                .collect(Collectors.joining(", ", "(", ")"));
        Class<?> type = generated.getSuperclass();
        String candidates = matches.isEmpty() ? String.join(", ", available)
                : matches.stream().map(m -> signature(m.constructor())).collect(Collectors.joining(", "));
        throw new IllegalArgumentException((matches.isEmpty() ? "No constructor of " + type.getName()
                + " accepts the arguments " + given + ". Its constructors take: "
                : "More than one constructor of " + type.getName() + " accepts the arguments " + given + ": ")
                + candidates + ". Pass arguments that match exactly one, or call the generated constructor directly,"
                + " which the compiler checks: new " + generated.getSimpleName() + "(registry, ...).");
    }

    /** The parameters of a generated constructor after the registry, for messages: {@code (String, int...)}. */
    private static String signature(Constructor<?> constructor) {
        Class<?>[] parameters = constructor.getParameterTypes();
        List<String> names = new ArrayList<>();
        for (int i = 1; i < parameters.length; i++) {
            String name = parameters[i].getSimpleName();
            names.add(constructor.isVarArgs() && i == parameters.length - 1
                    ? name.substring(0, name.length() - 2) + "..." : name);
        }
        return "(" + String.join(", ", names) + ")";
    }

    /** True if {@code arguments[1..count)} fit {@code parameters[1..count)}; index 0 is the registry. */
    private static boolean accepts(Class<?>[] parameters, Object[] arguments, int count) {
        for (int i = 1; i < count; i++) {
            if (!accepts(parameters[i], arguments[i])) {
                return false;
            }
        }
        return true;
    }

    private static boolean accepts(Class<?> parameter, Object argument) {
        return argument == null ? !parameter.isPrimitive() : wrapper(parameter).isInstance(argument);
    }

    private static Class<?> wrapper(Class<?> type) {
        if (!type.isPrimitive()) {
            return type;
        }
        return switch (type.getName()) {
            case "boolean" -> Boolean.class;
            case "byte" -> Byte.class;
            case "short" -> Short.class;
            case "char" -> Character.class;
            case "int" -> Integer.class;
            case "long" -> Long.class;
            case "float" -> Float.class;
            case "double" -> Double.class;
            default -> Void.class;
        };
    }
}
