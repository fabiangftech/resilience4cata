package dev.resilience4cata.micronaut;

import dev.resilience4cata.Resilient;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import org.jspecify.annotations.Nullable;

/**
 * Finds the classes the annotation processor generated: {@code I$Resilient} for an annotated interface
 * {@code I}, {@code C$Resilient} for an annotated class {@code C}. Results are cached per type, so each type
 * costs at most one class-loading attempt per application context, at bean creation, never per call.
 */
final class GeneratedClasses {

    /** Set by GraalVM's native image builder and in the image (what {@code ImageInfo} reads). */
    static final boolean NATIVE_IMAGE = System.getProperty("org.graalvm.nativeimage.imagecode") != null;

    private final Map<Class<?>, Optional<Class<?>>> cache = new ConcurrentHashMap<>();
    private final Map<String, Boolean> annotatedByName = new ConcurrentHashMap<>();

    /** The generated wrapper of an annotated interface, or {@code null}. */
    @Nullable Class<?> wrapperOf(Class<?> type) {
        Class<?> generated = generatedFor(type);
        return generated != null && type.isInterface() && type.isAssignableFrom(generated) ? generated : null;
    }

    /** The generated subclass of an annotated class, or {@code null}. */
    @Nullable Class<?> subclassOf(Class<?> type) {
        Class<?> generated = generatedFor(type);
        return generated != null && !type.isInterface() && generated.getSuperclass() == type ? generated : null;
    }

    /**
     * Whether the class named {@code className} has a generated subclass, without loading the class when it has none
     * (on the JVM, a resource lookup answers that). For names read from bean definitions before any bean exists.
     */
    boolean hasGeneratedSubclass(String className, ClassLoader loader) {
        if (skipped(className) || className.endsWith(Resilient.GENERATED_SUFFIX)) {
            return false;
        }
        return annotatedByName.computeIfAbsent(className, name -> {
            String generatedName = name + Resilient.GENERATED_SUFFIX;
            if (!NATIVE_IMAGE && loader.getResource(generatedName.replace('.', '/') + ".class") == null) {
                return false;
            }
            try {
                return subclassOf(Class.forName(name, false, loader)) != null;
            } catch (ClassNotFoundException | LinkageError e) {
                return false;
            }
        });
    }

    /** Whether {@code type} is a subclass generated by the processor. */
    boolean isGeneratedSubclass(Class<?> type) {
        Class<?> superclass = type.getSuperclass();
        return type.getName().endsWith(Resilient.GENERATED_SUFFIX) && superclass != null && subclassOf(superclass) == type;
    }

    private @Nullable Class<?> generatedFor(Class<?> type) {
        if (skipped(type.getName()) || type.getClassLoader() == null) {
            return null;
        }
        return cache.computeIfAbsent(type, GeneratedClasses::load).orElse(null);
    }

    /** JDK and framework classes: never annotated by the application. */
    static boolean skipped(String name) {
        return name.startsWith("java.") || name.startsWith("javax.") || name.startsWith("jakarta.")
                || name.startsWith("jdk.") || name.startsWith("io.micronaut.") || name.startsWith("io.netty.")
                || name.startsWith("io.micrometer.");
    }

    private static Optional<Class<?>> load(Class<?> type) {
        ClassLoader loader = type.getClassLoader();
        String name = type.getName() + Resilient.GENERATED_SUFFIX;
        // On the JVM a missing resource answers without the cost of a ClassNotFoundException; a native image has
        // no class files as resources, but the processor's reachability metadata registers the generated class.
        if (!NATIVE_IMAGE && loader.getResource(name.replace('.', '/') + ".class") == null) {
            return Optional.empty();
        }
        try {
            return Optional.of(Class.forName(name, false, loader));
        } catch (ClassNotFoundException | LinkageError e) {
            return Optional.empty();
        }
    }
}
