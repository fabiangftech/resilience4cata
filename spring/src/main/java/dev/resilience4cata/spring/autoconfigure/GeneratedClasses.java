package dev.resilience4cata.spring.autoconfigure;

import dev.resilience4cata.Resilient;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import org.jspecify.annotations.Nullable;
import org.springframework.core.NativeDetector;

/**
 * Finds the classes the annotation processor generated: {@code I$Resilient} for an annotated interface
 * {@code I}, {@code C$Resilient} for an annotated class {@code C}. Results are cached per type, so each
 * type costs at most one class-loading attempt per application context.
 */
final class GeneratedClasses {

    private final Map<Class<?>, Optional<Class<?>>> cache = new ConcurrentHashMap<>();

    /** The generated wrapper of an annotated interface, or {@code null}. */
    @Nullable Class<?> wrapperOf(Class<?> type) {
        Class<?> generated = generatedFor(type);
        return generated != null && type.isInterface() && type.isAssignableFrom(generated) ? generated : null;
    }

    /** The generated subclass of an annotated class, or {@code null}. */
    @Nullable Class<?> subclassOf(Class<?> type) {
        Class<?> generated = generatedFor(type);
        return generated != null && !type.isInterface() && generated.getSuperclass() == type ? generated : null;
    }

    /** Whether {@code type} is a class generated by the processor (a wrapper or a subclass). */
    boolean isGenerated(Class<?> type) {
        if (!type.getName().endsWith(Resilient.GENERATED_SUFFIX)) {
            return false;
        }
        Class<?> superclass = type.getSuperclass();
        if (superclass != null && subclassOf(superclass) == type) {
            return true;
        }
        for (Class<?> implemented : type.getInterfaces()) {
            if (wrapperOf(implemented) == type) {
                return true;
            }
        }
        return false;
    }

    private @Nullable Class<?> generatedFor(Class<?> type) {
        if (skipped(type.getName()) || type.getClassLoader() == null) {
            return null;
        }
        return cache.computeIfAbsent(type, GeneratedClasses::load).orElse(null);
    }

    /** JDK, Spring and proxy classes: never annotated by the application. */
    static boolean skipped(String name) {
        return name.startsWith("java.") || name.startsWith("javax.") || name.startsWith("jakarta.")
                || name.startsWith("jdk.") || name.startsWith("org.springframework.") || name.contains("$$");
    }

    private static Optional<Class<?>> load(Class<?> type) {
        ClassLoader loader = type.getClassLoader();
        String name = type.getName() + Resilient.GENERATED_SUFFIX;
        // On the JVM a missing resource answers without the cost of a ClassNotFoundException; a native image has
        // no class files as resources, but the processor's reachability metadata registers the generated class.
        if (!NativeDetector.inNativeImage() && loader.getResource(name.replace('.', '/') + ".class") == null) {
            return Optional.empty();
        }
        try {
            return Optional.of(Class.forName(name, false, loader));
        } catch (ClassNotFoundException | LinkageError e) {
            return Optional.empty();
        }
    }
}
